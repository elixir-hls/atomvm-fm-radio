// From usb-rtl-sdr-tang25k f50cc0c (rtl/).
// fir_dec.v — decimating FIR, one multiply-accumulate per clock (one DSP).
//
//   y[m] = (sum_{k=0}^{TAPS-1} h[k] * x[DEC*m + PHASE - k]) >>> SH      (x before the start = 0)
//
// The input samples go into a ring buffer (2^AW entries); after the input sample whose index
// n has n % DEC == PHASE, the sum for that output runs over TAPS clocks. Same arithmetic as
// eval/stereo_model.py fir_decim. Timing: the next output must not start before this one is
// done (TAPS + 4 clocks), and at most 2^AW - TAPS inputs may arrive during a sum.
// Coefficients: TABLE 1 = fir1_h, 2 = fir2_h from fm_tables.vh (generated by
// eval/stereo_model.py). Case functions, not $readmemh: on hardware the FIR output came out
// ~0 with the coefficients loaded by $readmemh into an inferred memory.
module fir_dec #(
    parameter TAPS  = 32,
    parameter DEC   = 4,
    parameter PHASE = 3,
    parameter IW    = 16,          // input width
    parameter OW    = 18,          // output width
    parameter SH    = 15,          // output shift
    parameter SAT   = 1,           // 1: saturate to OW bits, 0: truncate (caller knows it fits)
    parameter AW    = 6,           // ring buffer address width
    parameter TABLE = 1
) (
    input  wire                 clk,
    input  wire                 in_valid,
    input  wire signed [IW-1:0] in,
    output reg                  out_valid = 1'b0,
    output reg  signed [OW-1:0] out = 0
);
    localparam ACCW = IW + 18 + 9;

    reg signed [IW-1:0] buffer [0:(1<<AW)-1];
`include "fm_tables.vh"
`ifdef __ICARUS__
    // sim: the model treats samples before the start as 0 (in hardware only the first TAPS
    // outputs see the power-up contents)
    integer i;
    initial for (i = 0; i < (1 << AW); i = i + 1) buffer[i] = 0;
`endif

    reg [AW-1:0] wp = 0, base = 0;
    reg [7:0]    cnt = 0;
    reg          busy = 1'b0;
    reg [8:0]    k = 0;

    always @(posedge clk) begin
        if (in_valid) begin
            buffer[wp] <= in;
            wp  <= wp + 1'b1;
            cnt <= (cnt == DEC - 1) ? 8'd0 : cnt + 8'd1;
            if (cnt == PHASE) begin
                base <= wp;
                busy <= 1'b1;
                k    <= 0;
            end
        end
        if (busy && !(in_valid && cnt == PHASE)) begin
            k <= k + 1'b1;
            if (k == TAPS - 1) busy <= 1'b0;
        end
    end

    // pipeline: read buffer / coefficient -> multiply -> accumulate
    reg signed [IW-1:0]   rd = 0;
    reg signed [17:0]     cf = 0;
    reg                   v1 = 1'b0, l1 = 1'b0, f1 = 1'b0;
    reg signed [IW+17:0]  prod = 0;
    reg                   v2 = 1'b0, l2 = 1'b0, f2 = 1'b0;
    reg signed [ACCW-1:0] acc = 0;
    reg                   v3 = 1'b0;
    always @(posedge clk) begin
        rd <= buffer[base - k[AW-1:0]];
        cf <= (TABLE == 1) ? fir1_h(k[4:0]) : fir2_h(k[7:0]);
        v1 <= busy;
        l1 <= busy && k == TAPS - 1;
        f1 <= busy && k == 0;
        prod <= rd * cf;
        v2 <= v1; l2 <= l1; f2 <= f1;
        // (written as two plain assignments: Gowin synthesised `(f2 ? $signed({ACCW{1'b0}}) :
        //  acc) + prod` as if acc were always 0, keeping only the last product on hardware)
        if (v2) begin
            if (f2) acc <= prod;
            else    acc <= acc + prod;
        end
        v3 <= v2 && l2;
    end

    wire signed [ACCW-1:0] sh = acc >>> SH;
    always @(posedge clk) begin
        out_valid <= v3;
        if (v3) begin
            if (SAT && sh > $signed({1'b0, {(OW-1){1'b1}}}))
                out <= {1'b0, {(OW-1){1'b1}}};
            else if (SAT && sh < $signed({1'b1, {(OW-1){1'b0}}}))
                out <= {1'b1, {(OW-1){1'b0}}};
            else
                out <= sh[OW-1:0];
        end
    end
endmodule
